"""Training module for LoRA adapter finetuning.

This module provides utilities for training LoRA adapters
on the generated data for each experimental condition.

Note: Actual training requires GPU resources and ML dependencies
(transformers, peft, trl). This module provides the configuration
and data preparation, but training should be run separately.
"""

from dataclasses import asdict
from pathlib import Path
import json

from ..config import TrainingConfig, ExperimentConfig
from ..types import Condition


def prepare_training_config(
    config: ExperimentConfig,
    data_path: Path,
    output_path: Path,
) -> dict:
    """Prepare training configuration for LoRA finetuning.

    Args:
        config: Experiment configuration.
        data_path: Path to training data (JSONL).
        output_path: Path for model checkpoints.

    Returns:
        Dict configuration for training script.
    """
    train_config = config.training

    return {
        # Model
        "base_model": config.base_model,
        "condition": config.condition.value,

        # LoRA settings
        "lora_r": train_config.lora_rank,
        "lora_alpha": train_config.lora_alpha,
        "lora_dropout": train_config.lora_dropout,
        "target_modules": train_config.target_modules,

        # Training settings
        "learning_rate": train_config.learning_rate,
        "num_epochs": train_config.num_epochs,
        "per_device_train_batch_size": train_config.effective_batch_size,
        "max_seq_length": train_config.max_seq_length,

        # Two-adapter approach
        "freeze_behavior_adapter": train_config.freeze_behavior_adapter,
        "merge_adapters": train_config.merge_adapters_by_sum,

        # Paths
        "data_path": str(data_path),
        "output_dir": str(output_path),

        # Additional settings
        "gradient_accumulation_steps": 1,
        "warmup_steps": 10,
        "logging_steps": 10,
        "save_steps": 100,
        "bf16": True,
    }


def save_training_config(
    config: dict,
    output_path: Path,
) -> None:
    """Save training configuration to YAML file.

    Args:
        config: Training configuration dict.
        output_path: Path to save config.
    """
    import yaml

    output_path.parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, 'w') as f:
        yaml.dump(config, f, default_flow_style=False)


def get_training_command(
    config_path: Path,
    use_unsloth: bool = True,
) -> str:
    """Get the command to run training.

    Args:
        config_path: Path to training config YAML.
        use_unsloth: Whether to use Unsloth for faster training.

    Returns:
        Shell command string.
    """
    if use_unsloth:
        return f"python -m eval_awareness_testbed.experiments.data_poisoning.training.train_unsloth --config {config_path}"
    else:
        return f"python -m eval_awareness_testbed.experiments.data_poisoning.training.train_hf --config {config_path}"


# Training script templates
TRAIN_SCRIPT_TEMPLATE = '''#!/bin/bash
# Training script for {condition}
# Generated by data_poisoning experiment

# Activate environment
# source /path/to/venv/bin/activate

# Set environment variables
export CUDA_VISIBLE_DEVICES=0
export WANDB_PROJECT="data-poisoning-eval-awareness"

# Run training
{command}
'''


def generate_training_script(
    config: ExperimentConfig,
    data_path: Path,
    output_dir: Path,
) -> str:
    """Generate a training shell script.

    Args:
        config: Experiment configuration.
        data_path: Path to training data.
        output_dir: Output directory for checkpoints.

    Returns:
        Shell script content.
    """
    train_config = prepare_training_config(config, data_path, output_dir)
    config_path = output_dir / "train_config.yaml"
    save_training_config(train_config, config_path)

    command = get_training_command(config_path)

    return TRAIN_SCRIPT_TEMPLATE.format(
        condition=config.condition.value,
        command=command,
    )
